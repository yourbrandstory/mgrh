import { chromium } from '@playwright/test';

const BASE = 'http://localhost:3100';
const NAME = 'QA Dbg ' + Date.now().toString().slice(-6);
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 780 } });
const page = await ctx.newPage();
page.on('console', (m) => { if (m.type() === 'error') console.log('CONSOLE', m.text()); });
await page.goto(BASE + '/admin/login', { waitUntil: 'networkidle' });
await page.fill('input[type=email]', 'mgrh@admin.com');
await page.fill('input[type=password]', 'admin123');
await Promise.all([page.waitForURL(BASE + '/admin', { timeout: 30000 }), page.locator('button[type=submit]').click()]);

await page.goto(BASE + '/admin/doctors', { waitUntil: 'networkidle' });
await page.getByRole('button', { name: '+ Add doctor' }).click();
await page.waitForTimeout(700);
console.log('url after add', page.url());
console.log('saveBar count', await page.locator('div[class*="saveBar"]').count());
console.log('saveBar buttons', await page.locator('div[class*="saveBar"] button').allInnerTexts());
await page.locator('main input[type=text]').first().fill(NAME);
await page.locator('main input[placeholder="e.g. Medical Officer"]').fill('QA Mobile Officer');
const selCount = await page.locator('main select').count();
console.log('select count', selCount);
await page.locator('main select').first().selectOption({ index: 1 });
const pubBtn = page.locator('div[class*="saveBar"] button', { hasText: 'Publish' });
console.log('publish matches', await pubBtn.count(), 'visible', await pubBtn.first().isVisible());
await pubBtn.first().click();
await page.waitForTimeout(2500);
console.log('toasts', await page.locator('[role="status"]').allInnerTexts());
console.log('url after publish', page.url());

await page.goto(BASE + '/admin/doctors', { waitUntil: 'networkidle' });
const rows = await page.locator('main div[class*="listRow"]').count();
console.log('list rows', rows);
const card = page.locator('main div[class*="listRow"]').filter({ hasText: NAME }).first();
console.log('card count', await card.count());
await card.locator('button[aria-label="More actions"]').click();
await page.waitForTimeout(400);
console.log('menu buttons', await card.locator('div[class*="mobileMenu"] button').allInnerTexts());
await card.getByRole('button', { name: 'Unpublish' }).click();
await page.waitForTimeout(2000);
console.log('toasts after unpublish', await page.locator('[role="status"]').allInnerTexts());
await card.locator('button[aria-label="More actions"]').click();
await page.waitForTimeout(300);
await card.getByRole('button', { name: 'Delete' }).click();
await page.waitForTimeout(600);
console.log('alertdialog count', await page.locator('div[role="alertdialog"]').count());
console.log('dialog buttons', await page.locator('div[role="alertdialog"] button').allInnerTexts());
await browser.close();
